CREATE TABLE mensagens (
    chat          TEXT   NOT NULL,
    id            TEXT   NOT NULL,
    remetente     TEXT   NOT NULL,
    remetente_alt TEXT   NOT NULL,
    texto         TEXT   NOT NULL,
    enviada_em    BIGINT NOT NULL,
    PRIMARY KEY (chat, id)
);

CREATE INDEX mensagens_por_remetente ON mensagens (chat, remetente);

CREATE INDEX mensagens_por_remetente_alt ON mensagens (chat, remetente_alt);

CREATE INDEX mensagens_por_data ON mensagens (chat, enviada_em);

CREATE INDEX mensagens_por_idade ON mensagens (enviada_em);

CREATE TABLE risadas (
    chat          TEXT   NOT NULL,
    id            TEXT   NOT NULL,
    quem_riu      TEXT   NOT NULL,
    alvo          TEXT   NOT NULL,
    alvo_alt      TEXT   NOT NULL,
    mensagem_alvo TEXT   NOT NULL,
    enviada_em    BIGINT NOT NULL,
    PRIMARY KEY (chat, id)
);

CREATE INDEX risadas_por_data ON risadas (chat, enviada_em);

CREATE TABLE ia_memorias (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat      TEXT   NOT NULL,
    texto     TEXT   NOT NULL CHECK (texto <> ''),
    criada_em BIGINT NOT NULL
);

CREATE INDEX ia_memorias_por_chat ON ia_memorias (chat);

CREATE TABLE ia_respostas (
    chat        TEXT   NOT NULL,
    id          TEXT   NOT NULL,
    pergunta_id TEXT   NOT NULL,
    texto       TEXT   NOT NULL,
    enviada_em  BIGINT NOT NULL,
    PRIMARY KEY (chat, id)
);

CREATE INDEX ia_respostas_por_data ON ia_respostas (chat, enviada_em);

CREATE INDEX ia_respostas_por_pergunta ON ia_respostas (chat, pergunta_id);

