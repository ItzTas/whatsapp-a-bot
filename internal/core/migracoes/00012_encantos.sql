-- +goose Up
CREATE TABLE encantos (
    chat     TEXT   NOT NULL,
    alvo     TEXT   NOT NULL,
    tipo     TEXT   NOT NULL,
    autor    TEXT   NOT NULL,
    ate      BIGINT NOT NULL,
    parte    BIGINT NOT NULL DEFAULT 0,
    bonus    BIGINT NOT NULL DEFAULT 0,
    teto     BIGINT NOT NULL DEFAULT 0,
    continuo BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (chat, alvo, tipo)
);

CREATE TABLE encantos_avisos (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat      TEXT   NOT NULL,
    tipo      TEXT   NOT NULL,
    alvo      TEXT   NOT NULL,
    alvo_jid  TEXT   NOT NULL,
    autor     TEXT   NOT NULL,
    autor_jid TEXT   NOT NULL,
    valor     BIGINT NOT NULL,
    repasse   BIGINT NOT NULL,
    aplicado  BIGINT NOT NULL DEFAULT 0
);

-- +goose StatementBegin
CREATE FUNCTION encantos_no_ganho() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    agora BIGINT := floor(extract(epoch FROM now()))::bigint;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM encantos e
        WHERE e.chat = NEW.chat AND e.alvo = NEW.pessoa AND (e.parte > 0 OR e.bonus > 0) AND e.ate > agora
    ) THEN
        RETURN NULL;
    END IF;

    INSERT INTO encantos_avisos (chat, tipo, alvo, alvo_jid, autor, autor_jid, valor, repasse)
    SELECT NEW.chat, e.tipo, NEW.pessoa, NEW.jid, e.autor, c.jid, (NEW.saldo - OLD.saldo) * e.parte / 100, 1
    FROM encantos e
    JOIN carteiras c ON c.chat = e.chat AND c.pessoa = e.autor
    WHERE e.chat = NEW.chat AND e.alvo = NEW.pessoa AND e.autor <> e.alvo AND e.parte > 0
      AND e.ate > agora
      AND (NEW.saldo - OLD.saldo) * e.parte / 100 > 0;

    INSERT INTO encantos_avisos (chat, tipo, alvo, alvo_jid, autor, autor_jid, valor, repasse)
    SELECT NEW.chat, e.tipo, NEW.pessoa, NEW.jid, e.autor, COALESCE(c.jid, NEW.jid), LEAST((NEW.saldo - OLD.saldo) * e.bonus / 100, e.teto), 0
    FROM encantos e
    LEFT JOIN carteiras c ON c.chat = e.chat AND c.pessoa = e.autor
    WHERE e.chat = NEW.chat AND e.alvo = NEW.pessoa AND e.bonus > 0
      AND e.ate > agora
      AND LEAST((NEW.saldo - OLD.saldo) * e.bonus / 100, e.teto) > 0;

    UPDATE carteiras SET saldo = saldo + (
        SELECT SUM(a.valor) FROM encantos_avisos a
        WHERE a.chat = NEW.chat AND a.alvo = NEW.pessoa AND a.aplicado = 0 AND a.repasse = 1 AND a.autor = carteiras.pessoa
    )
    WHERE chat = NEW.chat AND pessoa IN (
        SELECT a.autor FROM encantos_avisos a
        WHERE a.chat = NEW.chat AND a.alvo = NEW.pessoa AND a.aplicado = 0 AND a.repasse = 1
    );

    UPDATE carteiras SET saldo = saldo + COALESCE((
        SELECT SUM(CASE WHEN a.repasse = 1 THEN -a.valor ELSE a.valor END) FROM encantos_avisos a
        WHERE a.chat = NEW.chat AND a.alvo = NEW.pessoa AND a.aplicado = 0
    ), 0)
    WHERE chat = NEW.chat AND pessoa = NEW.pessoa;

    DELETE FROM encantos WHERE chat = NEW.chat AND alvo = NEW.pessoa AND continuo = 0 AND tipo IN (
        SELECT a.tipo FROM encantos_avisos a
        WHERE a.chat = NEW.chat AND a.alvo = NEW.pessoa AND a.aplicado = 0
    );

    UPDATE encantos_avisos SET aplicado = 1 WHERE chat = NEW.chat AND alvo = NEW.pessoa AND aplicado = 0;
    RETURN NULL;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER encantos_no_ganho AFTER UPDATE OF saldo ON carteiras
FOR EACH ROW WHEN (NEW.saldo > OLD.saldo AND pg_trigger_depth() = 0)
EXECUTE FUNCTION encantos_no_ganho();

-- +goose Down
DROP TRIGGER IF EXISTS encantos_no_ganho ON carteiras;
DROP FUNCTION IF EXISTS encantos_no_ganho();
DROP TABLE IF EXISTS encantos_avisos;
DROP TABLE IF EXISTS encantos;
