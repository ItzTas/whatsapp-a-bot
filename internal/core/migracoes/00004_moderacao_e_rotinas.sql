CREATE TABLE aniversarios (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat       TEXT   NOT NULL,
    pessoa     TEXT   NOT NULL,
    pessoa_alt TEXT   NOT NULL,
    dia        BIGINT NOT NULL CHECK (dia BETWEEN 1 AND 31),
    mes        BIGINT NOT NULL CHECK (mes BETWEEN 1 AND 12),
    ultimo_ano BIGINT NOT NULL DEFAULT 0,
    criado_em  BIGINT NOT NULL,
    UNIQUE (chat, pessoa)
);

CREATE INDEX aniversarios_por_alt ON aniversarios (chat, pessoa_alt);

CREATE INDEX aniversarios_por_mes ON aniversarios (mes, ultimo_ano);

