CREATE TABLE lembretes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat        TEXT   NOT NULL,
    hora        BIGINT NOT NULL CHECK (hora BETWEEN 0 AND 23),
    minuto      BIGINT NOT NULL CHECK (minuto BETWEEN 0 AND 59),
    texto       TEXT   NOT NULL CHECK (texto <> ''),
    mencoes     TEXT   NOT NULL DEFAULT '',
    criador     TEXT   NOT NULL,
    criador_alt TEXT   NOT NULL,
    criado_em   BIGINT NOT NULL,
    proximo     BIGINT NOT NULL
);

CREATE INDEX lembretes_por_chat ON lembretes (chat);

CREATE INDEX lembretes_por_proximo ON lembretes (proximo);

